function tr_message(string $message): string
{
    global $current_lang, $message_translations;
    if ($current_lang !== 'am') {
        return $message;
    }
    foreach ($message_translations as $english => $amharic) {
        if (str_starts_with($message, $english)) {
            return $amharic . substr($message, strlen($english));
        }
    }
    return $message;
}
